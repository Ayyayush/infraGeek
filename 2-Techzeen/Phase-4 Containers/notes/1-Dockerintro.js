/**
 * 🐳 Docker – Containerization Platform (DevOps Basics)
 *
 * --------------------------------------------------
 * 🔹 Docker kya hai?
 *
 * Docker ek **containerization platform** hai
 * jo hume allow karta hai:
 * 👉 Application ko uski **saari dependencies** ke saath
 * 👉 ek **isolated environment** me package karne ka
 *
 * Is isolated environment ko **Container** kehte hain.
 *
 * 
 * 
 * --------------------------------------------------
 * 🔹 Container kya hota hai?
 *
 * Container ek lightweight box hota hai jisme:
 * - Application
 * - Libraries
 * - Dependencies
 * - Configurations
 *
 * sab kuch bundled hota hai.
 *
 * 👉 "Runs anywhere" concept yahin se aata hai
 *
 * --------------------------------------------------
 * 🔹 Docker kya karta hai? (Simple words me)
 *
 * ❌ Pehle problem:
 * - Mere laptop pe chal raha hai
 * - Tumhare laptop pe nahi chal raha
 *
 * ✅ Docker solution:
 * - Ek container bana do
 * - Har jagah same tarike se chalega
 *
 * --------------------------------------------------
 * 🔹 Docker ki zarurat kyun padti hai?
 *
 * 1️⃣ Environment consistency
 * - Dev, Test, Prod sab jagah same setup
 *
 * 2️⃣ Fast setup
 * - Ek command me app run
 *
 * 3️⃣ Lightweight
 * - VM se kaafi halka hota hai
 *
 * 4️⃣ Easy deployment
 * - Cloud, server, local – sab jagah same
 *
 * --------------------------------------------------
 * 🔹 Docker kahan use hota hai?
 *
 * - Development environment
 * - Testing
 * - CI/CD pipelines
 * - Cloud deployments
 * - Microservices architecture
 *
 * 👉 Almost har modern company Docker use karti hai
 *
 * --------------------------------------------------
 * 🔹 Docker vs Virtual Machine (short idea)
 *
 * Virtual Machine:
 * - Apna OS hota hai
 * - Heavy & slow
 *
 * Docker Container:
 * - Host OS share karta hai
 * - Lightweight & fast ⚡
 *
 * --------------------------------------------------
 * 🔹 Docker ka use technology pe depend karta hai?
 *
 * ❌ NAHI ❌
 *
 * Chahe tum:
 * - PHP / Laravel
 * - Java / .NET
 * - MERN Stack
 * - Python / Django
 *
 * 👉 Docker sab ke liye SAME hota hai
 *
 * Isliye:
 * "Tech stack kuch bhi ho,
 * Docker aana hi chahiye"
 *
 * --------------------------------------------------
 * 🔹 Docker interview-ready definition:
 *
 * "Docker is a containerization platform that allows
 * applications to be packaged with all their
 * dependencies into isolated environments called
 * containers, ensuring consistency across systems."
 *
 * 
 * --------------------------------------------------
 * ✅ Summary:
 * - Docker = container platform
 * - Container = isolated app environment
 * - Fast, lightweight, portable
 * - Tech stack se independent
 *
 * 🔥 Docker DevOps ka MOST IMPORTANT tool hai!
 */
